using Microsoft.EntityFrameworkCore;
namespace Movers.DAL.Persistence;

/// <summary>Idempotent upgrade: the management assistant's saved conversations (script 042). Runs before CompanySchema, which indexes the table as a company table.</summary>
public static class AssistantSchema
{
    public static async Task Apply(MoversDbContext db)
    {
        if (db.Database.IsSqlServer()) await db.Database.ExecuteSqlRawAsync(SqlServer);
        else if (db.Database.IsNpgsql()) await db.Database.ExecuteSqlRawAsync(PostgreSql);
        // SQLite is only used for fresh test databases, which EnsureCreated builds from the current model.
    }

    public const string SqlServer = """
        IF OBJECT_ID(N'dbo.AssistantConversations', N'U') IS NULL
        BEGIN
            CREATE TABLE [dbo].[AssistantConversations] ([SerialNo] INT IDENTITY(1,1) NOT NULL CONSTRAINT [PK_AssistantConversations] PRIMARY KEY, [Id] UNIQUEIDENTIFIER NOT NULL, [TenantId] UNIQUEIDENTIFIER NOT NULL, [CompanyId] UNIQUEIDENTIFIER NULL,
                [UserId] UNIQUEIDENTIFIER NOT NULL, [Title] NVARCHAR(120) NOT NULL, [MessagesJson] NVARCHAR(MAX) NOT NULL, [CreatedAtUtc] DATETIMEOFFSET NOT NULL, [UpdatedAtUtc] DATETIMEOFFSET NOT NULL,
                CONSTRAINT [FK_AssistantConversations_Tenants] FOREIGN KEY ([TenantId]) REFERENCES [dbo].[Tenants]([Id]));
            CREATE UNIQUE INDEX [IX_AssistantConversations_Id] ON [dbo].[AssistantConversations]([Id]);
            CREATE INDEX [IX_AssistantConversations_TenantId_UserId] ON [dbo].[AssistantConversations]([TenantId], [UserId]);
            CREATE INDEX [IX_AssistantConversations_TenantId] ON [dbo].[AssistantConversations]([TenantId]);
        END
        """;

    public const string PostgreSql = """
        CREATE TABLE IF NOT EXISTS "AssistantConversations" ("SerialNo" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "Id" uuid NOT NULL, "TenantId" uuid NOT NULL REFERENCES "Tenants"("Id"), "CompanyId" uuid NULL,
            "UserId" uuid NOT NULL, "Title" varchar(120) NOT NULL, "MessagesJson" text NOT NULL, "CreatedAtUtc" timestamp with time zone NOT NULL, "UpdatedAtUtc" timestamp with time zone NOT NULL);
        CREATE UNIQUE INDEX IF NOT EXISTS "IX_AssistantConversations_Id" ON "AssistantConversations"("Id");
        CREATE INDEX IF NOT EXISTS "IX_AssistantConversations_TenantId_UserId" ON "AssistantConversations"("TenantId", "UserId");
        CREATE INDEX IF NOT EXISTS "IX_AssistantConversations_TenantId" ON "AssistantConversations"("TenantId");
        """;
}
