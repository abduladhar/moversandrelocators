using Microsoft.EntityFrameworkCore;
namespace Movers.DAL.Persistence;

/// <summary>Idempotent upgrade for databases created before survey attachments and customer change requests (script 019).</summary>
public static class SurveyMediaSchema
{
    public static async Task Apply(MoversDbContext db)
    {
        if (db.Database.IsSqlServer())
        {
            await db.Database.ExecuteSqlRawAsync("""
                IF COL_LENGTH(N'dbo.Surveys', N'CustomerChangeRequestJson') IS NULL ALTER TABLE [dbo].[Surveys] ADD [CustomerChangeRequestJson] nvarchar(max) NULL;
                IF COL_LENGTH(N'dbo.Surveys', N'CustomerChangeRequestedAtUtc') IS NULL ALTER TABLE [dbo].[Surveys] ADD [CustomerChangeRequestedAtUtc] datetimeoffset NULL;
                IF OBJECT_ID(N'dbo.SurveyAttachments', N'U') IS NULL
                BEGIN
                    CREATE TABLE [dbo].[SurveyAttachments] ([SerialNo] INT IDENTITY(1,1) NOT NULL CONSTRAINT [PK_SurveyAttachments] PRIMARY KEY, [Id] UNIQUEIDENTIFIER NOT NULL, [TenantId] UNIQUEIDENTIFIER NOT NULL, [SurveyId] UNIQUEIDENTIFIER NOT NULL, [Source] NVARCHAR(20) NOT NULL, [UploadedBy] NVARCHAR(160) NOT NULL, [OriginalFileName] NVARCHAR(255) NOT NULL, [ContentType] NVARCHAR(150) NOT NULL, [DeclaredSizeBytes] BIGINT NOT NULL, [StoredSizeBytes] BIGINT NULL, [S3ObjectKey] NVARCHAR(700) NOT NULL, [IsUploaded] BIT NOT NULL, [CreatedAtUtc] DATETIMEOFFSET NOT NULL, [UploadedAtUtc] DATETIMEOFFSET NULL,
                        CONSTRAINT [FK_SurveyAttachments_Tenants] FOREIGN KEY ([TenantId]) REFERENCES [dbo].[Tenants]([Id]), CONSTRAINT [FK_SurveyAttachments_Surveys] FOREIGN KEY ([SurveyId]) REFERENCES [dbo].[Surveys]([Id]) ON DELETE CASCADE);
                    CREATE UNIQUE INDEX [IX_SurveyAttachments_Id] ON [dbo].[SurveyAttachments]([Id]);
                    CREATE INDEX [IX_SurveyAttachments_SurveyId_SerialNo] ON [dbo].[SurveyAttachments]([SurveyId],[SerialNo]);
                    CREATE INDEX [IX_SurveyAttachments_TenantId] ON [dbo].[SurveyAttachments]([TenantId]);
                END
                """);
        }
        else if (db.Database.IsNpgsql())
        {
            await db.Database.ExecuteSqlRawAsync("""
                ALTER TABLE "Surveys" ADD COLUMN IF NOT EXISTS "CustomerChangeRequestJson" text NULL;
                ALTER TABLE "Surveys" ADD COLUMN IF NOT EXISTS "CustomerChangeRequestedAtUtc" timestamp with time zone NULL;
                CREATE TABLE IF NOT EXISTS "SurveyAttachments" ("SerialNo" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "Id" uuid NOT NULL, "TenantId" uuid NOT NULL REFERENCES "Tenants"("Id"), "SurveyId" uuid NOT NULL REFERENCES "Surveys"("Id") ON DELETE CASCADE, "Source" varchar(20) NOT NULL, "UploadedBy" varchar(160) NOT NULL, "OriginalFileName" varchar(255) NOT NULL, "ContentType" varchar(150) NOT NULL, "DeclaredSizeBytes" bigint NOT NULL, "StoredSizeBytes" bigint NULL, "S3ObjectKey" varchar(700) NOT NULL, "IsUploaded" boolean NOT NULL, "CreatedAtUtc" timestamp with time zone NOT NULL, "UploadedAtUtc" timestamp with time zone NULL);
                CREATE UNIQUE INDEX IF NOT EXISTS "IX_SurveyAttachments_Id" ON "SurveyAttachments"("Id");
                CREATE INDEX IF NOT EXISTS "IX_SurveyAttachments_SurveyId_SerialNo" ON "SurveyAttachments"("SurveyId","SerialNo");
                CREATE INDEX IF NOT EXISTS "IX_SurveyAttachments_TenantId" ON "SurveyAttachments"("TenantId");
                """);
        }
        // SQLite is only used for fresh test databases, which EnsureCreated builds from the current model.
    }
}
