using Microsoft.EntityFrameworkCore;
namespace Movers.DAL.Persistence;

/// <summary>Idempotent upgrade that adds expense receipts to existing databases (script 031).</summary>
public static class ExpenseAttachmentSchema
{
    public static async Task Apply(MoversDbContext db)
    {
        if (db.Database.IsSqlServer()) await db.Database.ExecuteSqlRawAsync(SqlServer);
        else if (db.Database.IsNpgsql()) await db.Database.ExecuteSqlRawAsync(PostgreSql);
        // SQLite is only used for fresh test databases, which EnsureCreated builds from the current model.
    }

    public const string SqlServer = """
        IF OBJECT_ID(N'dbo.ExpenseAttachments', N'U') IS NULL
        BEGIN
            CREATE TABLE [dbo].[ExpenseAttachments] ([SerialNo] INT IDENTITY(1,1) NOT NULL CONSTRAINT [PK_ExpenseAttachments] PRIMARY KEY, [Id] UNIQUEIDENTIFIER NOT NULL, [TenantId] UNIQUEIDENTIFIER NOT NULL, [Kind] NVARCHAR(20) NOT NULL, [ExpenseId] UNIQUEIDENTIFIER NOT NULL, [OriginalFileName] NVARCHAR(180) NOT NULL, [ContentType] NVARCHAR(160) NOT NULL, [DeclaredSizeBytes] BIGINT NOT NULL, [StoredSizeBytes] BIGINT NULL, [ObjectKey] NVARCHAR(700) NOT NULL, [IsUploaded] BIT NOT NULL, [IsDeleted] BIT NOT NULL, [UploadedBy] NVARCHAR(254) NOT NULL, [CreatedAtUtc] DATETIMEOFFSET NOT NULL, [UploadedAtUtc] DATETIMEOFFSET NULL,
                CONSTRAINT [FK_ExpenseAttachments_Tenants] FOREIGN KEY ([TenantId]) REFERENCES [dbo].[Tenants]([Id]));
            CREATE UNIQUE INDEX [IX_ExpenseAttachments_Id] ON [dbo].[ExpenseAttachments]([Id]);
            CREATE INDEX [IX_ExpenseAttachments_TenantId_ExpenseId] ON [dbo].[ExpenseAttachments]([TenantId],[ExpenseId]);
        END
        """;

    public const string PostgreSql = """
        CREATE TABLE IF NOT EXISTS "ExpenseAttachments" ("SerialNo" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "Id" uuid NOT NULL, "TenantId" uuid NOT NULL REFERENCES "Tenants"("Id"), "Kind" varchar(20) NOT NULL, "ExpenseId" uuid NOT NULL, "OriginalFileName" varchar(180) NOT NULL, "ContentType" varchar(160) NOT NULL, "DeclaredSizeBytes" bigint NOT NULL, "StoredSizeBytes" bigint NULL, "ObjectKey" varchar(700) NOT NULL, "IsUploaded" boolean NOT NULL, "IsDeleted" boolean NOT NULL, "UploadedBy" varchar(254) NOT NULL, "CreatedAtUtc" timestamp with time zone NOT NULL, "UploadedAtUtc" timestamp with time zone NULL);
        CREATE UNIQUE INDEX IF NOT EXISTS "IX_ExpenseAttachments_Id" ON "ExpenseAttachments"("Id");
        CREATE INDEX IF NOT EXISTS "IX_ExpenseAttachments_TenantId_ExpenseId" ON "ExpenseAttachments"("TenantId","ExpenseId");
        """;
}
