using Microsoft.EntityFrameworkCore;
namespace Movers.DAL.Persistence;

/// <summary>Idempotent upgrade for crew management: teams, their membership history, and the team snapshot held
/// on each packing and pickup assignment (script 027).</summary>
public static class CrewSchema
{
    public static async Task Apply(MoversDbContext db)
    {
        if (db.Database.IsSqlServer()) { foreach (var batch in System.Text.RegularExpressions.Regex.Split(SqlServer, @"^\s*GO\s*$", System.Text.RegularExpressions.RegexOptions.Multiline)) await db.Database.ExecuteSqlRawAsync(batch); }
        else if (db.Database.IsNpgsql()) await db.Database.ExecuteSqlRawAsync(PostgreSql);
        // SQLite is only used for fresh test databases, which EnsureCreated builds from the current model.
    }

    public const string SqlServer = """
        IF OBJECT_ID(N'dbo.Teams', N'U') IS NULL
        BEGIN
            CREATE TABLE [dbo].[Teams] ([SerialNo] INT IDENTITY(1,1) NOT NULL CONSTRAINT [PK_Teams] PRIMARY KEY, [Id] UNIQUEIDENTIFIER NOT NULL, [TenantId] UNIQUEIDENTIFIER NOT NULL, [Code] NVARCHAR(40) NOT NULL, [Name] NVARCHAR(160) NOT NULL, [Kind] NVARCHAR(20) NOT NULL, [LeaderEmployeeId] UNIQUEIDENTIFIER NULL, [Notes] NVARCHAR(1000) NULL, [IsActive] BIT NOT NULL, [CreatedAtUtc] DATETIMEOFFSET NOT NULL, [UpdatedAtUtc] DATETIMEOFFSET NOT NULL, [Version] UNIQUEIDENTIFIER NOT NULL,
                CONSTRAINT [FK_Teams_Tenants] FOREIGN KEY ([TenantId]) REFERENCES [dbo].[Tenants]([Id]),
                CONSTRAINT [FK_Teams_Employees] FOREIGN KEY ([LeaderEmployeeId]) REFERENCES [dbo].[Employees]([Id]));
            CREATE UNIQUE INDEX [IX_Teams_Id] ON [dbo].[Teams]([Id]);
            CREATE UNIQUE INDEX [IX_Teams_TenantId_Code] ON [dbo].[Teams]([TenantId],[Code]);
        END
        GO
        IF OBJECT_ID(N'dbo.TeamMemberships', N'U') IS NULL
        BEGIN
            CREATE TABLE [dbo].[TeamMemberships] ([SerialNo] INT IDENTITY(1,1) NOT NULL CONSTRAINT [PK_TeamMemberships] PRIMARY KEY, [Id] UNIQUEIDENTIFIER NOT NULL, [TenantId] UNIQUEIDENTIFIER NOT NULL, [TeamId] UNIQUEIDENTIFIER NOT NULL, [EmployeeId] UNIQUEIDENTIFIER NOT NULL, [Role] NVARCHAR(60) NOT NULL, [JoinedAtUtc] DATETIMEOFFSET NOT NULL, [LeftAtUtc] DATETIMEOFFSET NULL, [RecordedBy] NVARCHAR(254) NOT NULL, [LeaveReason] NVARCHAR(500) NULL,
                CONSTRAINT [FK_TeamMemberships_Tenants] FOREIGN KEY ([TenantId]) REFERENCES [dbo].[Tenants]([Id]),
                CONSTRAINT [FK_TeamMemberships_Teams] FOREIGN KEY ([TeamId]) REFERENCES [dbo].[Teams]([Id]) ON DELETE CASCADE,
                CONSTRAINT [FK_TeamMemberships_Employees] FOREIGN KEY ([EmployeeId]) REFERENCES [dbo].[Employees]([Id]));
            CREATE UNIQUE INDEX [IX_TeamMemberships_Id] ON [dbo].[TeamMemberships]([Id]);
            CREATE INDEX [IX_TeamMemberships_Team] ON [dbo].[TeamMemberships]([TeamId],[LeftAtUtc]);
            CREATE INDEX [IX_TeamMemberships_Employee] ON [dbo].[TeamMemberships]([EmployeeId],[LeftAtUtc]);
        END
        GO
        IF COL_LENGTH(N'dbo.PickupAssignments', N'TeamId') IS NULL
            ALTER TABLE [dbo].[PickupAssignments] ADD [TeamId] UNIQUEIDENTIFIER NULL, [TeamName] NVARCHAR(160) NULL,
                [AssignedAtUtc] DATETIMEOFFSET NOT NULL CONSTRAINT [DF_PickupAssignments_AssignedAtUtc] DEFAULT SYSDATETIMEOFFSET();
        GO
        IF COL_LENGTH(N'dbo.PackingJobCrew', N'TeamId') IS NULL
            ALTER TABLE [dbo].[PackingJobCrew] ADD [TeamId] UNIQUEIDENTIFIER NULL, [TeamName] NVARCHAR(160) NULL,
                [AssignedAtUtc] DATETIMEOFFSET NOT NULL CONSTRAINT [DF_PackingJobCrews_AssignedAtUtc] DEFAULT SYSDATETIMEOFFSET();
        GO
        IF COL_LENGTH(N'dbo.PickupAssignments', N'TeamId') IS NOT NULL AND NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_PickupAssignments_Team')
            CREATE INDEX [IX_PickupAssignments_Team] ON [dbo].[PickupAssignments]([TeamId]);
        GO
        IF COL_LENGTH(N'dbo.PackingJobCrew', N'TeamId') IS NOT NULL AND NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_PackingJobCrews_Team')
            CREATE INDEX [IX_PackingJobCrews_Team] ON [dbo].[PackingJobCrew]([TeamId]);
        """;

    public const string PostgreSql = """
        CREATE TABLE IF NOT EXISTS "Teams" ("SerialNo" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "Id" uuid NOT NULL, "TenantId" uuid NOT NULL REFERENCES "Tenants"("Id"), "Code" varchar(40) NOT NULL, "Name" varchar(160) NOT NULL, "Kind" varchar(20) NOT NULL, "LeaderEmployeeId" uuid NULL REFERENCES "Employees"("Id"), "Notes" varchar(1000) NULL, "IsActive" boolean NOT NULL, "CreatedAtUtc" timestamp with time zone NOT NULL, "UpdatedAtUtc" timestamp with time zone NOT NULL, "Version" uuid NOT NULL);
        CREATE UNIQUE INDEX IF NOT EXISTS "IX_Teams_Id" ON "Teams"("Id");
        CREATE UNIQUE INDEX IF NOT EXISTS "IX_Teams_TenantId_Code" ON "Teams"("TenantId","Code");

        CREATE TABLE IF NOT EXISTS "TeamMemberships" ("SerialNo" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "Id" uuid NOT NULL, "TenantId" uuid NOT NULL REFERENCES "Tenants"("Id"), "TeamId" uuid NOT NULL REFERENCES "Teams"("Id") ON DELETE CASCADE, "EmployeeId" uuid NOT NULL REFERENCES "Employees"("Id"), "Role" varchar(60) NOT NULL, "JoinedAtUtc" timestamp with time zone NOT NULL, "LeftAtUtc" timestamp with time zone NULL, "RecordedBy" varchar(254) NOT NULL, "LeaveReason" varchar(500) NULL);
        CREATE UNIQUE INDEX IF NOT EXISTS "IX_TeamMemberships_Id" ON "TeamMemberships"("Id");
        CREATE INDEX IF NOT EXISTS "IX_TeamMemberships_Team" ON "TeamMemberships"("TeamId","LeftAtUtc");
        CREATE INDEX IF NOT EXISTS "IX_TeamMemberships_Employee" ON "TeamMemberships"("EmployeeId","LeftAtUtc");

        ALTER TABLE "PickupAssignments" ADD COLUMN IF NOT EXISTS "TeamId" uuid NULL;
        ALTER TABLE "PickupAssignments" ADD COLUMN IF NOT EXISTS "TeamName" varchar(160) NULL;
        ALTER TABLE "PickupAssignments" ADD COLUMN IF NOT EXISTS "AssignedAtUtc" timestamp with time zone NOT NULL DEFAULT now();
        ALTER TABLE "PackingJobCrew" ADD COLUMN IF NOT EXISTS "TeamId" uuid NULL;
        ALTER TABLE "PackingJobCrew" ADD COLUMN IF NOT EXISTS "TeamName" varchar(160) NULL;
        ALTER TABLE "PackingJobCrew" ADD COLUMN IF NOT EXISTS "AssignedAtUtc" timestamp with time zone NOT NULL DEFAULT now();
        CREATE INDEX IF NOT EXISTS "IX_PickupAssignments_Team" ON "PickupAssignments"("TeamId");
        CREATE INDEX IF NOT EXISTS "IX_PackingJobCrews_Team" ON "PackingJobCrew"("TeamId");
        """;
}
