using Microsoft.EntityFrameworkCore;
namespace Movers.DAL.Persistence;

/// <summary>Idempotent upgrade that adds the sales lead inventory to existing databases (script 032).</summary>
public static class LeadInventorySchema
{
    public static async Task Apply(MoversDbContext db)
    {
        if (db.Database.IsSqlServer()) await db.Database.ExecuteSqlRawAsync(SqlServer);
        else if (db.Database.IsNpgsql()) await db.Database.ExecuteSqlRawAsync(PostgreSql);
        // SQLite is only used for fresh test databases, which EnsureCreated builds from the current model.
    }

    public const string SqlServer = """
        IF OBJECT_ID(N'dbo.SalesLeadInventoryItems', N'U') IS NULL
        BEGIN
            CREATE TABLE [dbo].[SalesLeadInventoryItems] ([SerialNo] INT IDENTITY(1,1) NOT NULL CONSTRAINT [PK_SalesLeadInventoryItems] PRIMARY KEY, [Id] UNIQUEIDENTIFIER NOT NULL, [TenantId] UNIQUEIDENTIFIER NOT NULL, [SalesLeadId] UNIQUEIDENTIFIER NOT NULL, [Kind] NVARCHAR(10) NOT NULL, [Room] NVARCHAR(80) NULL, [Name] NVARCHAR(160) NOT NULL, [Quantity] INT NOT NULL, [UnitCbm] DECIMAL(12,3) NOT NULL, [Fragile] BIT NOT NULL, [Handling] NVARCHAR(300) NULL, [Notes] NVARCHAR(1000) NULL, [SourceAttachmentId] UNIQUEIDENTIFIER NULL, [CreatedAtUtc] DATETIMEOFFSET NOT NULL,
                CONSTRAINT [FK_SalesLeadInventoryItems_Tenants] FOREIGN KEY ([TenantId]) REFERENCES [dbo].[Tenants]([Id]), CONSTRAINT [FK_SalesLeadInventoryItems_SalesLeads] FOREIGN KEY ([SalesLeadId]) REFERENCES [dbo].[SalesLeads]([Id]) ON DELETE CASCADE);
            CREATE UNIQUE INDEX [IX_SalesLeadInventoryItems_Id] ON [dbo].[SalesLeadInventoryItems]([Id]);
            CREATE INDEX [IX_SalesLeadInventoryItems_SalesLeadId] ON [dbo].[SalesLeadInventoryItems]([SalesLeadId]);
            CREATE INDEX [IX_SalesLeadInventoryItems_TenantId] ON [dbo].[SalesLeadInventoryItems]([TenantId]);
        END
        """;

    public const string PostgreSql = """
        CREATE TABLE IF NOT EXISTS "SalesLeadInventoryItems" ("SerialNo" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "Id" uuid NOT NULL, "TenantId" uuid NOT NULL REFERENCES "Tenants"("Id"), "SalesLeadId" uuid NOT NULL REFERENCES "SalesLeads"("Id") ON DELETE CASCADE, "Kind" varchar(10) NOT NULL, "Room" varchar(80) NULL, "Name" varchar(160) NOT NULL, "Quantity" integer NOT NULL, "UnitCbm" numeric(12,3) NOT NULL, "Fragile" boolean NOT NULL, "Handling" varchar(300) NULL, "Notes" varchar(1000) NULL, "SourceAttachmentId" uuid NULL, "CreatedAtUtc" timestamp with time zone NOT NULL);
        CREATE UNIQUE INDEX IF NOT EXISTS "IX_SalesLeadInventoryItems_Id" ON "SalesLeadInventoryItems"("Id");
        CREATE INDEX IF NOT EXISTS "IX_SalesLeadInventoryItems_SalesLeadId" ON "SalesLeadInventoryItems"("SalesLeadId");
        CREATE INDEX IF NOT EXISTS "IX_SalesLeadInventoryItems_TenantId" ON "SalesLeadInventoryItems"("TenantId");
        """;
}
