using Movers.Domain.Tenants;
using Movers.Services.Tenancy;
using Movers.Services.Tenants;

namespace Movers.Api.Tests;

public sealed class TenantServiceTests
{
    [Fact]
    public async Task Create_rejects_duplicate_slug_in_service_layer()
    {
        var repository = new FakeTenantRepository();
        repository.Add(new Tenant("Existing", "existing", null, null, null));
        var service = new TenantService(repository, new TenantContext());

        await Assert.ThrowsAsync<DuplicateTenantSlugException>(() =>
            service.CreateAsync(new SaveTenantCommand("Another", " Existing ", null, null, null), default));
    }

    [Fact]
    public async Task Create_persists_normalized_tenant_through_repository()
    {
        var repository = new FakeTenantRepository();
        var service = new TenantService(repository, new TenantContext());

        var result = await service.CreateAsync(
            new SaveTenantCommand("  Atlas Movers ", " Atlas-Movers ", null, null, null), default);

        Assert.Equal("Atlas Movers", result.Name);
        Assert.Equal("atlas-movers", result.Slug);
        Assert.Equal(0, result.SerialNo); // Generated by the database, not application code.
        Assert.Single(repository.Items);
        Assert.Equal(1, repository.SaveCount);
    }

    private sealed class FakeTenantRepository : ITenantRepository
    {
        public List<Tenant> Items { get; } = [];
        public int SaveCount { get; private set; }

        public Task<IReadOnlyList<Tenant>> ListAsync(CancellationToken cancellationToken) =>
            Task.FromResult<IReadOnlyList<Tenant>>(Items);

        public Task<Tenant?> GetAsync(Guid id, bool trackChanges, CancellationToken cancellationToken) =>
            Task.FromResult(Items.SingleOrDefault(x => x.Id == id));

        public Task<Tenant?> FindActiveAsync(Guid? id, string? slug, CancellationToken cancellationToken) =>
            Task.FromResult(Items.SingleOrDefault(x => x.IsActive && (id == x.Id || slug == x.Slug)));

        public Task<bool> SlugExistsAsync(string slug, Guid? excludingId, CancellationToken cancellationToken) =>
            Task.FromResult(Items.Any(x => x.Slug == slug && (!excludingId.HasValue || x.Id != excludingId)));

        public Task<(IReadOnlyList<Tenant> Items, int Total)> SearchAsync(TenantListFilter filter, Movers.Services.Common.ListQuery query, CancellationToken cancellationToken) =>
            Task.FromResult<(IReadOnlyList<Tenant> Items, int Total)>((Items, Items.Count));

        public Task<TenantListSummary> SummaryAsync(CancellationToken cancellationToken) =>
            Task.FromResult(new TenantListSummary(Items.Count, Items.Count(x => x.IsActive), Items.Count(x => !x.IsActive)));

        public void Add(Tenant tenant) => Items.Add(tenant);

        public Task SaveChangesAsync(CancellationToken cancellationToken)
        {
            SaveCount++;
            return Task.CompletedTask;
        }
    }
}
