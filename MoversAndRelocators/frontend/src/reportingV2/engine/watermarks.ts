/** Watermark text suggestions per report type. Any custom text is still allowed in the designer. */
const INVOICE = ['DRAFT', 'PROFORMA', 'FINAL', 'ORIGINAL', 'COPY', 'DUPLICATE', 'PAID', 'CANCELLED'];
const BILL = ['DRAFT', 'ORIGINAL', 'COPY', 'DUPLICATE', 'CANCELLED'];
const RECEIPT = ['ORIGINAL', 'COPY', 'DUPLICATE', 'PAID', 'CANCELLED'];
const MEMO = ['DRAFT', 'ORIGINAL', 'COPY', 'CANCELLED'];
const QUOTATION = ['DRAFT', 'FINAL', 'REVISED', 'ORIGINAL', 'COPY', 'EXPIRED'];
const OPERATIONS = ['ORIGINAL', 'COPY', 'DRAFT', 'FRAGILE'];
const STATEMENT = ['ORIGINAL', 'COPY', 'DRAFT', 'CONFIDENTIAL'];
export const GENERIC_WATERMARKS = ['DRAFT', 'ORIGINAL', 'COPY', 'DUPLICATE', 'CANCELLED', 'CONFIDENTIAL'];

const MAP: Record<string, string[]> = {
  INVOICE, BILL, RECEIPT, PAYMENT: RECEIPT, CREDIT_MEMO: MEMO, DEBIT_MEMO: MEMO, QUOTATION,
  PICKUP_RECEIPT: RECEIPT, BOX_LABELS: OPERATIONS, PACKING_LIST: OPERATIONS, WAREHOUSE_RECEIPT: OPERATIONS, JOB_MANIFEST: OPERATIONS, COST_REPORT: STATEMENT,
  PACKING_LABELS: OPERATIONS, PACKING_SHEET: OPERATIONS, PACKING_RECEIPT: RECEIPT, DELIVERY_NOTE: OPERATIONS, DELIVERY_RECEIPT: RECEIPT
};

export function watermarkNamesFor(type: string): string[] {
  return MAP[type] || (type.startsWith('ACCOUNTING_') ? STATEMENT : GENERIC_WATERMARKS);
}
